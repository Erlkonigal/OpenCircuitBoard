import { test, expect, type Page } from '../BrowserTest';
import { buildPath } from '../Paths';
async function ready(page: Page) {
    await page.goto('/');
    await expect(page.locator('canvas[aria-label="Circuit board"]')).toBeVisible();
    await page.waitForTimeout(250);
}
async function boardCenter(page: Page) {
    const box = (await page.getByTestId('board').boundingBox())!;
    return { x: box.x + box.width / 2, y: box.y + box.height / 2 };
}
test('design workspace, drawing, selection, clipboard and history', async ({ page }) => {
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await ready(page);
    await expect(page.getByTestId('left-dock')).toContainText('Components');
    await expect(page.getByTestId('right-dock')).toContainText('Inspector');
    await expect(page.getByRole('heading', { name: 'Start with a spark.' })).toBeVisible();
    await page.screenshot({ path: buildPath('SidebarCapture.png') });
    await page.screenshot({ path: buildPath('InterfaceCapture.png') });
    await page.screenshot({ path: buildPath('DefaultZoomCapture.png') });
    const center = await boardCenter(page);
    await page.getByRole('button', { name: 'Or', exact: true }).click();
    await page.mouse.move(center.x - 80, center.y);
    await page.mouse.down();
    await page.mouse.move(center.x + 80, center.y, { steps: 16 });
    await page.mouse.up();
    await expect(page.locator('.workspace-status')).toContainText('6 cells');
    await page.screenshot({ path: buildPath('Capture.png') });
    await page.mouse.move(center.x + 130, center.y + 60);
    await page.screenshot({ path: buildPath('SelectorCapture.png') });
    await page.keyboard.press('Control+z');
    await expect(page.locator('.workspace-status')).toContainText('0 cells');
    await page.keyboard.press('Control+u');
    await expect(page.locator('.workspace-status')).toContainText('6 cells');
    await page.keyboard.down('Shift');
    await page.mouse.move(center.x - 100, center.y - 40);
    await page.mouse.down();
    await page.mouse.move(center.x + 110, center.y + 50, { steps: 8 });
    await page.mouse.up();
    await page.keyboard.up('Shift');
    await expect(page.getByTestId('right-dock')).toContainText('6 cells');
    await page.screenshot({ path: buildPath('SelectionCapture.png') });
    await page.keyboard.press('Control+c');
    await expect(page.getByTestId('left-dock')).toContainText('Clipboard');
    await page.screenshot({ path: buildPath('ClipboardDockCapture.png') });
    await page.mouse.move(center.x - 80, center.y + 100);
    await expect(page.locator('.workspace-status')).toContainText('X -3');
    await page.keyboard.press('Control+v');
    await expect(page.locator('.canvas-context')).toContainText('Click to place');
    await page.screenshot({ path: buildPath('PastePreviewCapture.png') });
    await page.mouse.click(center.x - 80, center.y + 100);
    await expect(page.locator('.workspace-status')).toContainText('12 cells');
    await page.screenshot({ path: buildPath('PastedLayeringCapture.png') });
    await page.getByRole('button', { name: 'Fit board in view' }).click();
    await expect(page.getByRole('button', { name: 'Fit canvas', exact: true })).toHaveText('29%');
    await page.screenshot({ path: buildPath('BoardEdgeCapture.png') });
    expect(errors).toEqual([]);
});
test('component library and inspector configure colors and per-cell settings', async ({ page }) => {
    await ready(page);
    await page.getByRole('button', { name: 'Clock', exact: true }).click();
    await expect(page.getByLabel('Clock hold', { exact: true })).toBeVisible();
    await page.getByLabel('Clock hold', { exact: true }).fill('4');
    await page.screenshot({ path: buildPath('ClockSettingsCapture.png') });
    const center = await boardCenter(page);
    await page.mouse.click(center.x, center.y);
    await page.keyboard.down('Shift');
    await page.mouse.move(center.x - 8, center.y - 8);
    await page.mouse.down();
    await page.mouse.move(center.x + 30, center.y + 30);
    await page.mouse.up();
    await page.keyboard.up('Shift');
    await expect(page.getByTestId('right-dock')).toContainText('Selection');
    await page.getByLabel('Clock hold', { exact: true }).fill('7');
    await page.screenshot({ path: buildPath('SelectionSettingsCapture.png') });
    await page.getByRole('button', { name: 'Clear selection' }).click();
    await page.getByRole('button', { name: 'Trace', exact: true }).click();
    await page.getByRole('button', { name: 'traceMagenta', exact: true }).click();
    await expect(page.getByRole('button', { name: 'traceMagenta', exact: true })).toHaveAttribute('aria-pressed', 'true');
    await page.screenshot({ path: buildPath('TraceColorCapture.png') });
    await page.getByRole('button', { name: 'Bus', exact: true }).click();
    await page.getByRole('button', { name: 'busYellow', exact: true }).click();
    await page.screenshot({ path: buildPath('BusColorCapture.png') });
    await page.getByRole('button', { name: 'Latch', exact: true }).click();
    await page.getByText('Off', { exact: true }).click();
    await page.mouse.click(center.x + 64, center.y);
    await page.screenshot({ path: buildPath('InkStatesCapture.png') });
    await page.getByLabel('Search components').fill('xor');
    await expect(page.getByRole('button', { name: 'Clock', exact: true })).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Xor', exact: true })).toBeVisible();
});
test('canvas tools, panel toggles, activity and command menu', async ({ page }) => {
    await ready(page);
    await page.getByRole('button', { name: 'Toggle component library' }).click();
    await expect(page.getByTestId('left-dock')).toHaveCount(0);
    await page.getByRole('button', { name: 'Show components' }).click();
    await page.getByRole('button', { name: 'Toggle inspector' }).click();
    await expect(page.getByTestId('right-dock')).toHaveCount(0);
    await page.getByRole('button', { name: 'Toggle inspector' }).click();
    await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Fit canvas', exact: true })).toHaveText('55%');
    await page.getByRole('button', { name: 'Fit board in view' }).click();
    await expect(page.getByRole('button', { name: 'Fit canvas', exact: true })).toHaveText('29%');
    await page.getByLabel('Canvas Width', { exact: true }).fill('48');
    await page.getByRole('button', { name: 'Apply canvas size' }).click();
    await expect(page.locator('.workspace-status')).toContainText('48 x 28');
    await page.screenshot({ path: buildPath('CanvasResizeCapture.png') });
    await page.getByRole('button', { name: 'Toggle activity' }).click();
    await expect(page.getByTestId('activity-panel')).toBeVisible();
    await page.screenshot({ path: buildPath('ActivityCapture.png') });
    await page.getByRole('button', { name: 'Commands', exact: false }).click();
    await page.getByLabel('Search commands').fill('clipboard');
    await page.screenshot({ path: buildPath('CommandsCapture.png') });
    await page.getByRole('button', { name: 'Show clipboard', exact: true }).last().click();
    await expect(page.getByTestId('left-dock')).toContainText('Clipboard');
    await page.getByRole('button', { name: 'Keyboard shortcuts', exact: true }).click();
    await expect(page.getByRole('dialog')).toContainText('Ctrl Z / U');
});
